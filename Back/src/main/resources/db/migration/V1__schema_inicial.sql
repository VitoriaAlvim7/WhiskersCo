
CREATE TABLE tutor (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo    BOOLEAN,
    cpf      VARCHAR(255),
    endereco VARCHAR(255),
    nome     VARCHAR(255),
    telefone VARCHAR(255)
);

CREATE TABLE produto (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao    VARCHAR(255),
    nome         VARCHAR(255),
    preco        DOUBLE PRECISION,
    quantidade   INTEGER,
    tipo_produto VARCHAR(255)
);

CREATE TABLE funcionario (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agenda              VARCHAR(255),
    ativo               BOOLEAN,
    email               VARCHAR(255),
    funcao              VARCHAR(255),
    nome                VARCHAR(255),
    senha               VARCHAR(255),
    status_funcionario  VARCHAR(255)
);

CREATE TABLE animal_adocao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alergias      VARCHAR(255),
    ativo         BOOLEAN,
    idade         INTEGER,
    informacoes   VARCHAR(255),
    nome          VARCHAR(255),
    peso          DOUBLE PRECISION,
    raca          VARCHAR(255),
    status_adocao VARCHAR(255),
    unidade_idade VARCHAR(255)
);

CREATE TABLE paciente (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alergias      VARCHAR(255),
    ativo         BOOLEAN,
    idade         INTEGER,
    informacoes   VARCHAR(255),
    nome          VARCHAR(255),
    peso          DOUBLE PRECISION,
    raca          VARCHAR(255),
    unidade_idade VARCHAR(255),
    tutor_id      BIGINT REFERENCES tutor(id)
);

CREATE TABLE consulta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora       TIMESTAMP(6),
    motivo          VARCHAR(255),
    status          VARCHAR(255),
    funcionario_id  BIGINT REFERENCES funcionario(id),
    paciente_id     BIGINT REFERENCES paciente(id)
);

CREATE TABLE receituario (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_emissao DATE,
    prescricao   VARCHAR(255),
    consulta_id  BIGINT UNIQUE REFERENCES consulta(id)
);

CREATE TABLE transacao_caixa (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora         TIMESTAMP(6),
    metodo_pagamento  VARCHAR(255),
    tipo              VARCHAR(255),
    valor_total       DOUBLE PRECISION,
    consulta_id       BIGINT REFERENCES consulta(id),
    funcionario_id    BIGINT REFERENCES funcionario(id)
);

CREATE TABLE item_transacao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantidade    INTEGER,
    produto_id    BIGINT REFERENCES produto(id),
    transacao_id  BIGINT REFERENCES transacao_caixa(id)
);
