
CREATE TABLE agenda_funcionario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funcionario_id BIGINT       NOT NULL REFERENCES funcionario(id) ON DELETE CASCADE,
    dia_semana     VARCHAR(255) NOT NULL,
    hora_inicio    TIME         NOT NULL,
    hora_fim       TIME         NOT NULL
);

CREATE INDEX idx_agenda_funcionario_funcionario ON agenda_funcionario (funcionario_id);

WITH parsed AS (
    SELECT f.id AS funcionario_id,
           regexp_match(f.agenda, '^(Seg a Sex|Ter a Sab) das ([0-9]{1,2})h as ([0-9]{1,2})h$') AS m
    FROM funcionario f
    WHERE f.agenda IS NOT NULL
)
INSERT INTO agenda_funcionario (funcionario_id, dia_semana, hora_inicio, hora_fim)
SELECT p.funcionario_id,
       dias.dia,
       ((p.m)[2] || ':00')::time,
       ((p.m)[3] || ':00')::time
FROM parsed p
CROSS JOIN LATERAL unnest(
    CASE (p.m)[1]
        WHEN 'Seg a Sex' THEN ARRAY['MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY']
        WHEN 'Ter a Sab' THEN ARRAY['TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY']
    END
) AS dias(dia)
WHERE p.m IS NOT NULL;

COMMENT ON COLUMN funcionario.agenda IS
    'Legado (item 10): texto livre substituido por agenda_funcionario. Mantido so como historico.';
